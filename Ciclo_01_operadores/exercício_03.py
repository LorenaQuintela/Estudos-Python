'''Exercício 3 -> Considere que o salário seja 2000 e os gastos sejam:
aluguel = 700
alimentação = 400
transporte = 200
Calcule quanto dinheiro sobrou.
'''
salario = 2000
aluguel = 700
alimentacao = 400
transporte = 200

sobra_total = salario - aluguel - alimentacao - transporte

print(f"Sobrou R$ {sobra_total} reais.")