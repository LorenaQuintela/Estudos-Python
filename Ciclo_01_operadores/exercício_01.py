''' Criar duas variáveis e mostrar as operações a seguir:
- Soma          - Divisão Inteira
- Subtração     - Resto
- Multiplicação - Potência
- Divisão
'''
numero1 = 20
numero2 = 5

resultado_soma = numero1 + numero2 
resultado_subtracacao = numero1 - numero2
resultado_multiplicacao = numero1 * numero2
resultado_divisao = numero1 / numero2
resultado_divisao_inteira = numero1 // numero2
resultado_resto = numero1 % numero2
resultado_potencia = numero1 ** numero2

print(f"Resultado da soma: {resultado_soma}")
print(f"Resultado da Subtração: {resultado_subtracacao}")
print(f"Resultado da Multiplicação: {resultado_multiplicacao}")
print(f"Resultado da Divisão: {resultado_divisao}")
print(f"Resultado da Divisão Inteira: {resultado_divisao_inteira}")
print(f"Resultado do Resto da Divisão: {resultado_resto}")
print(f"Resultado da Potência: {resultado_potencia}")