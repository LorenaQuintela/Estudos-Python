'''Problema reverso
Uma pessoa tinha uma determinada quantidade de dinheiro.
Ela gastou R$ 135 e depois recebeu R$ 80. No final, ficou com R$ 545. 
- Quanto dinheiro ela tinha inicialmente? '''

gastou = 135
recebeu = 80
final = 545

dinheiro = final - recebeu
inicial = dinheiro + gastou

print(inicial)