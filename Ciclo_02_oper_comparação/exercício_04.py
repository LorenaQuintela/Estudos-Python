'''Temperatura
Durante um dia, a temperatura registrada foi de 32°C.
Responda no caderno:
1- A temperatura está acima de 30°C? True
2- A temperatura está abaixo de 25°C? False
3- A temperatura é exatamente 32°C? True
4- A temperatura é diferente de 28°C? True'''
temperatura = 32

print("A temperatura está acima de 30°C? ", temperatura > 30)
print("A temperatura está abaixo de 25°C? ", temperatura < 25)
print("A temperatura é exatamente 32°C? ", temperatura == 32)
print("A temperatura é diferente de 28°C? ", temperatura != 28 )
