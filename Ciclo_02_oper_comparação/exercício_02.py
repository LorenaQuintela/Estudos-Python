'''Comparando duas pessoas
Ana tem 27 anos.
Carlos tem 31 anos.
1- Ana é mais velha que Carlos? False
2- Carlos é mais velho que Ana? True
3- As idade são iguais? False
4- As idades são diferentes? True'''

idade_ana = 27
idade_carlos = 31

print("Ana é mais velha que Carlos? ", idade_ana > idade_carlos)
print("Carlos é mais velho que Ana? ", idade_carlos > idade_ana)
print("As idade são iguais? ", idade_ana == idade_carlos)
print("As idades são diferentes? ", idade_ana != idade_carlos)